"""Figure: synthetic ID cards, ground-truth masks and forensic heatmaps.

Run `python examples/quickstart.py` first (writes PPMs to examples/output/), then:
    python examples/plot_gallery.py        # needs matplotlib and Pillow -> docs/gallery.png
All cards are synthetic, generated by doc_forgery.CardGenerator(seed=7).
"""
import os
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from PIL import Image

HERE = os.path.dirname(__file__)
OUT = os.path.join(HERE, "output")
ROWS = [("pristine", "Pristine"), ("copy-move", "Copy-move forgery"), ("spliced", "Spliced forgery")]
COLS = [("", "Synthetic card"), ("_mask", "Ground-truth forged region"), ("_heatmap", "Forensic heatmap")]
BLUE, RED = "#2e86ab", "#e4572e"

fig, axes = plt.subplots(3, 3, figsize=(11, 8.2))
for r, (kind, rname) in enumerate(ROWS):
    for c, (suffix, cname) in enumerate(COLS):
        ax = axes[r][c]
        ax.imshow(Image.open(os.path.join(OUT, f"{kind}{suffix}.ppm")))
        ax.set_xticks([]); ax.set_yticks([])
        for s in ax.spines.values():
            s.set_color(BLUE if c < 2 else RED); s.set_linewidth(1.5)
        if r == 0:
            ax.set_title(cname, fontsize=11)
        if c == 0:
            ax.set_ylabel(rname, fontsize=11)
fig.suptitle("Synthetic ID-document forgery: card, mask and forensic heatmap per kind",
             x=0.01, ha="left", fontweight="bold")
fig.text(0.01, 0.01, "Synthetic data: cards generated by doc_forgery.CardGenerator (seed 7); no real documents. "
         "Heatmap is the repo's pure-Python forensic detector, shown as written by quickstart.py.",
         fontsize=7, color="#666")
fig.tight_layout(rect=(0, 0.03, 1, 0.95))
fig.savefig(os.path.join(HERE, "..", "docs", "gallery.png"), dpi=130)
